#!/usr/bin/env python3
"""Inline the SAKSI datasets into live-demo/data.js for the static demo.

The JSON files under data/ stay the single source of truth; this script only
re-packages them so the browser build has no fetch/CORS dependency.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "live-demo", "data.js")

FILES = ["staff.json", "documents.json", "chats.json", "drugs.json", "permissions.json"]


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


def main():
    payload = {name.replace(".json", ""): load(name) for name in FILES}

    # Users offered in the demo switcher — chosen to show the ACL gradient.
    payload["demoUsers"] = ["STF-005", "STF-001", "STF-003", "STF-015"]

    payload["suggestions"] = [
        {"q": "Berapa stok Amoksisilin 500mg sekarang?", "tag": "bukti"},
        {"q": "Apa itu Proyek Cakalang?", "tag": "batas akses"},
        {"q": "Apa isi template surat rujukan?", "tag": "injeksi"},
        {"q": "Jam berapa poli buka?", "tag": "konflik"},
        {"q": "Apa SOP deteksi dini gangguan jiwa?", "tag": "ACL per dokumen"},
        {"q": "Berapa sisa cuti tahunan saya?", "tag": "kepegawaian"},
        {"q": "Berapa anggaran Proyek Bahari?", "tag": "keuangan"},
    ]

    payload["engineVersion"] = "v5"

    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    js = "// AUTO-GENERATED by tools/build_data.py — do not edit by hand.\n"
    js += "window.SAKSI_DATA = " + body + ";\n"

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)

    size = os.path.getsize(OUT)
    print(f"wrote {OUT}  ({size/1024:.1f} KB)")
    for k in ["staff", "documents", "chats", "drugs"]:
        print(f"  {k}: {len(payload[k])}")


if __name__ == "__main__":
    main()
